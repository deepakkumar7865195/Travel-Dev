export const sortedPosts = [...posts].sort(
  (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
);

export const blogCategories = Array.from(new Set(sortedPosts.map((p) => p.category)));

export function postsByCategory(category?: string) {
  if (!category || category === "All") return sortedPosts;
  return sortedPosts.filter((p) => p.category === category);
}

export function getPost(slug: string) {
  return posts.find((p) => p.slug === slug);
}

export function relatedPosts(slug: string, limit = 2) {
  return sortedPosts.filter((p) => p.slug !== slug).slice(0, limit);
}

export function formatDate(iso: string) {
  return new Date(iso).toLocaleDateString("en-IN", {
    day: "numeric",
    month: "short",
    year: "numeric",
  });
}
