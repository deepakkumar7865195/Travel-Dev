const unique = [...new Set(IDS)];
const ok = [];
await mkdir(OUT, { recursive: true });

async function head(url) {
  try {
    const r = await fetch(url, { method: "HEAD" });
    return r.ok;
  } catch {
    return false;
  }
}

let i = 0;
for (const id of unique) {
  i++;
  const url = `https://images.unsplash.com/photo-${id}?fm=jpg&fit=crop&w=${W}&q=${Q}`;
  if (!(await head(url))) continue;
  try {
    const res = await fetch(url);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.byteLength < 15000) continue;
    const name = `p${String(ok.length + 1).padStart(3, "0")}.jpg`;
    await writeFile(path.join(OUT, name), buf);
    ok.push({ name, id, kb: Math.round(buf.byteLength / 1024) });
  } catch (e) {
    console.log("err", id, e.message);
  }
}

await writeFile(path.resolve("public/images/raw/_manifest.json"), JSON.stringify(ok, null, 2));
